/**
 * Generates a high-resolution 1080x560 Shareable Night Ticket PNG using HTML5 Canvas.
 * Uses Web Share API (navigator.share with files) when supported, or triggers a PNG download.
 */
export async function shareOrDownloadNightTicket({
  film,
  backupFilm,
  timeline,
  moodObj
}) {
  if (!film || !timeline) return false;

  const canvas = document.createElement('canvas');
  canvas.width = 1080;
  canvas.height = 560;
  const ctx = canvas.getContext('2d');

  const c1 = film.gradient?.[0] || moodObj?.beamColor || '#FFB347';
  const c2 = film.gradient?.[1] || moodObj?.accentColor || '#7209B7';

  // Background
  ctx.fillStyle = '#09090f';
  ctx.fillRect(0, 0, 1080, 560);

  // Ticket body gradient
  const grad = ctx.createLinearGradient(0, 0, 1080, 560);
  grad.addColorStop(0, '#141422');
  grad.addColorStop(1, '#1d1830');
  ctx.fillStyle = grad;
  ctx.beginPath();
  ctx.roundRect(36, 36, 1008, 488, 28);
  ctx.fill();

  // Accent top bar
  const barGrad = ctx.createLinearGradient(36, 36, 1044, 36);
  barGrad.addColorStop(0, c1);
  barGrad.addColorStop(1, c2);
  ctx.fillStyle = barGrad;
  ctx.beginPath();
  ctx.roundRect(36, 36, 1008, 12, [28, 28, 0, 0]);
  ctx.fill();

  // Perforation divider line at x = 760
  ctx.save();
  ctx.strokeStyle = 'rgba(255,255,255,0.22)';
  ctx.lineWidth = 3;
  ctx.setLineDash([10, 10]);
  ctx.beginPath();
  ctx.moveTo(750, 56);
  ctx.lineTo(750, 504);
  ctx.stroke();
  ctx.restore();

  // Left section content
  ctx.fillStyle = c1;
  ctx.font = 'bold 18px sans-serif';
  ctx.fillText('LIGHTS DOWN // OFFICIAL SCREENING TICKET', 76, 98);

  ctx.fillStyle = '#F6F5F2';
  ctx.font = 'bold 44px sans-serif';
  const titleText = film.title.length > 26 ? film.title.slice(0, 25) + '…' : film.title;
  ctx.fillText(titleText, 76, 158);

  ctx.fillStyle = '#B8B5C8';
  ctx.font = '600 21px sans-serif';
  ctx.fillText(
    `${film.year} • ${film.language} • ${film.runtime} min • ${film.genres.join(' / ')}`,
    76,
    198
  );

  // Specs row
  ctx.fillStyle = 'rgba(255,255,255,0.06)';
  ctx.beginPath();
  ctx.roundRect(76, 228, 634, 86, 14);
  ctx.fill();

  ctx.fillStyle = '#9E9BAE';
  ctx.font = 'bold 14px sans-serif';
  ctx.fillText('HOOK SPEED', 100, 256);
  ctx.fillText('BRAIN BATTERY', 300, 256);
  ctx.fillText('SNACK PAIRING', 490, 256);

  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 20px sans-serif';
  ctx.fillText(`${film.hookMinutes} min grab`, 100, 288);
  ctx.fillText(`Level ${film.brainBattery}/5`, 300, 288);
  const snackShort = (film.snack || '').slice(0, 22);
  ctx.fillText(snackShort, 490, 288);

  // Backup Reel box
  if (backupFilm) {
    ctx.fillStyle = 'rgba(0, 245, 212, 0.09)';
    ctx.beginPath();
    ctx.roundRect(76, 336, 634, 82, 14);
    ctx.fill();

    ctx.fillStyle = '#00F5D4';
    ctx.font = 'bold 15px sans-serif';
    ctx.fillText('20-MINUTE RULE // PRE-LOADED BACKUP REEL', 100, 366);

    ctx.fillStyle = '#F6F5F2';
    ctx.font = 'bold 21px sans-serif';
    ctx.fillText(
      `${backupFilm.title} (${backupFilm.runtime}m • Hook in ${backupFilm.hookMinutes}m)`,
      100,
      398
    );
  }

  ctx.fillStyle = '#8C899E';
  ctx.font = '15px sans-serif';
  ctx.fillText('Generated by Lights Down — 90-Second Decision-to-Action Movie Engine', 76, 480);

  // Right stub content (Timeline)
  ctx.fillStyle = c1;
  ctx.font = 'bold 16px sans-serif';
  ctx.fillText('ADMIT ALL // STUB', 785, 98);

  ctx.fillStyle = '#9E9BAE';
  ctx.font = 'bold 14px sans-serif';
  ctx.fillText('REEL STARTS AT', 785, 152);
  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 34px monospace';
  ctx.fillText(timeline.startFormatted, 785, 192);

  ctx.fillStyle = '#9E9BAE';
  ctx.font = 'bold 14px sans-serif';
  ctx.fillText('20-MIN BAIL CHECK', 785, 248);
  ctx.fillStyle = '#00F5D4';
  ctx.font = 'bold 30px monospace';
  ctx.fillText(timeline.bailCheckFormatted, 785, 284);

  ctx.fillStyle = '#9E9BAE';
  ctx.font = 'bold 14px sans-serif';
  ctx.fillText('LIGHTS OUT BY', 785, 344);
  ctx.fillStyle = c1;
  ctx.font = 'bold 38px monospace';
  ctx.fillText(timeline.lightsOutFormatted, 785, 388);

  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 16px sans-serif';
  ctx.fillText(`★ ${film.rating} / 10`, 785, 476);

  const blob = await new Promise((resolve) => canvas.toBlob(resolve, 'image/png'));
  if (!blob) return false;

  const fileName = `lights-down-ticket-${film.id}.png`;
  const file = new File([blob], fileName, { type: 'image/png' });

  if (
    typeof navigator !== 'undefined' &&
    navigator.canShare &&
    navigator.canShare({ files: [file] })
  ) {
    try {
      await navigator.share({
        title: `Tonight's Screening: ${film.title}`,
        text: `Lights Down ticket locked: ${film.title} (Starts ${timeline.startFormatted}, Backup: ${backupFilm?.title || 'Ready'})`,
        files: [file]
      });
      return 'shared';
    } catch {
      // Fall through to download if user cancels or share fails
    }
  }

  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  return 'downloaded';
}
